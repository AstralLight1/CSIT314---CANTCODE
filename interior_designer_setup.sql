-- Run in Supabase SQL Editor. Existing user_accounts table is reused.
CREATE TABLE IF NOT EXISTS public.company_information (
  company_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  designer_id VARCHAR(100) NOT NULL UNIQUE REFERENCES public.user_accounts("userID"),
  company_name VARCHAR(150) NOT NULL,
  company_details TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.current_projects (
  project_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  designer_id VARCHAR(100) NOT NULL REFERENCES public.user_accounts("userID"),
  project_name VARCHAR(150) NOT NULL,
  project_details TEXT NOT NULL DEFAULT ''
);
